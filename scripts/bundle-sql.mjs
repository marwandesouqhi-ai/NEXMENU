import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, "..");
const migrationsDir = path.join(rootDir, "supabase", "migrations");
const bundleFile = path.join(rootDir, "supabase", "complete_setup.sql");

const isCheck = process.argv.includes("--check");

function generateBundle() {
  const files = fs
    .readdirSync(migrationsDir)
    .filter((f) => f.endsWith(".sql"))
    .sort();

  let output = `-- ==============================================================================
-- NEXMENU — COMPLETE SUPABASE SETUP SCRIPT (MIGRATIONS 001 TO ${String(files.length).padStart(3, "0")})
-- THIS IS A GENERATED FILE. DO NOT EDIT DIRECTLY.
-- Generated by: pnpm sql:bundle
-- Run: paste and execute in Supabase Dashboard > SQL Editor
-- ==============================================================================

`;

  for (const file of files) {
    const filePath = path.join(migrationsDir, file);
    const content = fs.readFileSync(filePath, "utf8").trim();
    output += `-- ------------------------------------------------------------------------------
-- FILE: ${file}
-- ------------------------------------------------------------------------------

${content}

`;
  }

  return output.replace(/\r\n/g, "\n");
}

const generated = generateBundle();

if (isCheck) {
  if (!fs.existsSync(bundleFile)) {
    console.error("Error: supabase/complete_setup.sql does not exist. Run 'pnpm sql:bundle'.");
    process.exit(1);
  }
  const existing = fs.readFileSync(bundleFile, "utf8").replace(/\r\n/g, "\n");
  if (existing.trim() !== generated.trim()) {
    console.error("Error: supabase/complete_setup.sql is out of date with supabase/migrations/. Run 'pnpm sql:bundle'.");
    process.exit(1);
  }
  console.log("✓ supabase/complete_setup.sql is up to date with all migrations.");
  process.exit(0);
} else {
  fs.writeFileSync(bundleFile, generated, "utf8");
  console.log(`✓ Generated supabase/complete_setup.sql successfully (${generated.length} bytes).`);
}
